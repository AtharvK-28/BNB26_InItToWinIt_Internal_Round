/** Shows which engine produced a result. */
export function SourceBadge({ source, className }: { source?: AiSource; className?: string }) {
  if (!source) return null;
  return (
    <span
      className={cn("inline-flex items-center gap-1 rounded-full border border-line-soft bg-white px-2 py-0.5 text-[11px] font-semibold text-ink-2", className)}
      title={source === "claude" ? "Generated by Claude" : "Generated by CreatorAI's built-in engine (add ANTHROPIC_API_KEY to use Claude)"}
    >
      <Sparkles className="size-3" />
      {source === "claude" ? "Claude" : "Built-in AI"}
    </span>
  );
}

export function EngineStatus({ className }: { className?: string }) {
  const s = useAiStatus();
  if (!s) return null;
  return (
    <span className={cn("inline-flex items-center gap-1.5 text-xs text-ink-2", className)}>
      <span className={cn("size-1.5 rounded-full", s.claude ? "bg-babu" : "bg-amber")} />
      {s.claude ? "Claude connected" : "Built-in AI · add API key for Claude"}
    </span>
  );
}

