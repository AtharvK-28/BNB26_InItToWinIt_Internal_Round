/** Tiny markdown renderer for AI text: **bold**, *italic*, bullet & numbered lists, paragraphs. */
export function Markdown({ text, className }: { text: string; className?: string }) {
  const blocks = text.replace(/\r/g, "").split(/\n{2,}/);
  return (
    <div className={cn("space-y-3 leading-relaxed", className)}>
      {blocks.map((block, bi) => {
        const lines = block.split("\n");
        const isList = lines.every((l) => /^\s*([-*•]|\d+\.)\s+/.test(l) || /^\s{2,}\S/.test(l));
        if (isList) {
          const ordered = /^\s*\d+\./.test(lines[0]);
          const items: string[] = [];
          for (const l of lines) {
            if (/^\s*([-*•]|\d+\.)\s+/.test(l)) items.push(l.replace(/^\s*([-*•]|\d+\.)\s+/, ""));
            else items[items.length - 1] += "\n" + l.trim();
          }
          const Tag = ordered ? "ol" : "ul";
          return (
            <Tag key={bi} className={cn("space-y-1.5 pl-5", ordered ? "list-decimal" : "list-disc", "marker:text-ink-3")}>
              {items.map((it, ii) => (
                <li key={ii} className="pl-1">
                  {it.split("\n").map((seg, si) => (
                    <Fragment key={si}>
                      {si > 0 && <br />}
                      <Inline text={seg} />
                    </Fragment>
                  ))}
                </li>
              ))}
            </Tag>
          );
        }
        return (
          <p key={bi}>
            {lines.map((l, li) => (
              <Fragment key={li}>
                {li > 0 && <br />}
                <Inline text={l} />
              </Fragment>
            ))}
          </p>
        );
      })}
    </div>
  );
}

function Inline({ text }: { text: string }) {
  const parts: ReactNode[] = [];
  const re = /(\*\*[^*]+\*\*|\*[^*\s][^*]*\*|_[^_]+_)/g;
  let last = 0;
  let m: RegExpExecArray | null;
  let i = 0;
  while ((m = re.exec(text))) {
    if (m.index > last) parts.push(text.slice(last, m.index));
    const t = m[0];
    if (t.startsWith("**")) parts.push(<strong key={i++} className="font-semibold text-ink">{t.slice(2, -2)}</strong>);
    else parts.push(<em key={i++}>{t.slice(1, -1)}</em>);
    last = m.index + t.length;
  }
  if (last < text.length) parts.push(text.slice(last));
  return <>{parts}</>;
}
