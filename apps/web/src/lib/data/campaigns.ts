function pickReviews(id: string, rating: number, months: string[]): BrandReview[] {
  const r = seeded(id);
  const pool = rating >= 4.6 ? POSITIVE : [...MIXED, ...POSITIVE.slice(0, 3)];
  const used = new Set<number>();
  const usedPeople = new Set<number>();
  const out: BrandReview[] = [];
  for (let i = 0; i < 6; i++) {
    let t = Math.floor(r() * pool.length);
    while (used.has(t)) t = (t + 1) % pool.length;
    used.add(t);
    let p = Math.floor(r() * REVIEWERS.length);
    while (usedPeople.has(p)) p = (p + 1) % REVIEWERS.length;
    usedPeople.add(p);
    const person = REVIEWERS[p];
    const isMixed = MIXED.includes(pool[t]);
    out.push({
      id: `${id}-r${i}`,
      author: person.name,
      avatar: person.avatar,
      meta: person.meta,
      date: months[i % months.length],
      rating: isMixed ? 3 + Math.round(r()) : 5 - (r() > 0.85 ? 1 : 0),
      text: pool[t],
    });
  }
  return out;
}

